package install

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const blockStart = "<!-- agent-toolkit:start -->"
const blockEnd = "<!-- agent-toolkit:end -->"
const conciseStart = "<!-- agent-toolkit:concise-output:start -->"
const conciseEnd = "<!-- agent-toolkit:concise-output:end -->"
const notice = "<!-- This configuration block is auto-generated by the agent-toolkit repository; manual edits may be overwritten. -->"
const conciseBlock = conciseStart + "\n## Concise output\n\nAt the start of every session, invoke the /concise-output skill. Treat its\ninstructions as standing guidance for all reader-facing responses. If it is\nnot already loaded, invoke it before answering.\n" + conciseEnd + "\n"

func guidanceBlock(root string, settings Settings) (string, error) {
	if !settings.FullTemplate && !settings.Concise && settings.Output == "" {
		return "", nil
	}
	var body strings.Builder
	body.WriteString(blockStart + "\n" + notice + "\n")
	if settings.FullTemplate {
		text, err := os.ReadFile(filepath.Join(root, ".agents/global/instructions.md"))
		if err != nil {
			return "", err
		}
		body.WriteString("\n" + string(text))
		if settings.Concise {
			body.WriteString("\n" + conciseBlock)
		}
		body.WriteString("\n## Installed Markdown output location\n\n")
		location := "<repo-root>/<branch-slug>/<skill-name>/..."
		if settings.Output != "" {
			location = settings.Output + "/<repo-slug>/<branch-slug>/<skill-name>/..."
		}
		fmt.Fprintf(&body, "Use `%s` for Markdown artifacts when the user does not provide an explicit path.\n", location)
		body.WriteString("Derive repository and branch slugs from the target Git repository, use `detached-<short-sha>` for detached HEADs, preserve all files from one skill invocation beneath its skill directory, and never overwrite an existing artifact without explicit direction. An explicit user-provided path always wins.\n")
		body.WriteString("\nWhen consuming Markdown from another skill, check the explicit path first, then the current Git repository and branch's producer-skill directory, then the configured centralized repository/branch/producer-skill directory, and finally documented legacy locations. Use the target repository's Git root rather than the working directory; do not search another repository or branch silently, and ask when multiple plausible artifacts remain.\n")
	} else {
		if settings.Output != "" {
			fmt.Fprintf(&body, "\n## Markdown output\n\nUse `%s/<repo-slug>/<branch-slug>/<skill-name>/...` for Markdown artifacts unless the user supplies a path.\n", settings.Output)
			body.WriteString("Keep each invocation under its skill directory and do not overwrite existing artifacts without explicit direction.\n")
		}
		if settings.Concise {
			body.WriteString("\n" + conciseBlock)
		}
	}
	body.WriteString("\n" + blockEnd + "\n")
	return body.String(), nil
}

// guidanceParts verifies every managed block and returns surrounding user text.
func (s *Service) guidanceParts(path string) (user, block string, count int, err error) {
	marker := filepath.Join(filepath.Dir(path), markerName)
	if err := regularOrAbsent(path); err != nil {
		return "", "", 0, err
	}
	if err := regularOrAbsent(marker); err != nil {
		return "", "", 0, err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) && !exists(marker) {
		return "", "", 0, nil
	}
	if err != nil {
		return "", "", 0, err
	}
	trusted := ""
	if exists(marker) {
		value, err := os.ReadFile(marker)
		if err != nil {
			return "", "", 0, err
		}
		lines := strings.Split(string(value), "\n")
		if len(lines) != 3 || lines[0] != s.Root || !strings.HasPrefix(lines[1], "GUIDANCE_BLOCK ") || lines[2] != "" {
			return "", "", 0, fmt.Errorf("untrusted guidance marker")
		}
		trusted = strings.TrimPrefix(lines[1], "GUIDANCE_BLOCK ")
	}
	var outside, inside strings.Builder
	ending := ""
	for _, line := range strings.SplitAfter(string(data), "\n") {
		if line == "" {
			continue
		}
		value := strings.TrimSuffix(line, "\n")
		if ending == "" {
			switch value {
			case blockStart:
				ending = blockEnd
			case conciseStart:
				ending = conciseEnd
			case blockEnd, conciseEnd:
				return "", "", 0, fmt.Errorf("unmatched guidance end")
			default:
				outside.WriteString(line)
				continue
			}
		} else if value == blockStart || (ending == conciseEnd && value == conciseStart) {
			return "", "", 0, fmt.Errorf("nested guidance block")
		}
		inside.WriteString(value + "\n")
		if value != ending {
			continue
		}
		block = inside.String()
		if trusted == "" || digest([]byte(block)) != trusted {
			return "", "", 0, fmt.Errorf("modified guidance block")
		}
		count++
		inside.Reset()
		ending = ""
	}
	if ending != "" || (trusted != "" && count == 0) {
		return "", "", 0, fmt.Errorf("incomplete guidance ownership")
	}
	return outside.String(), block, count, nil
}

func (s *Service) planGuidance(provider string, desired Settings) (*Operation, error) {
	_, path := s.destinations(provider)
	block := ""
	var err error
	if contains(desired.Providers, provider) {
		block, err = guidanceBlock(s.Root, desired)
		if err != nil {
			return nil, err
		}
	}
	user, current, count, err := s.guidanceParts(path)
	if err != nil {
		// Untouched user guidance without managed markers needs no removal.
		if block == "" && !exists(filepath.Join(filepath.Dir(path), markerName)) {
			data, readErr := os.ReadFile(path)
			if readErr == nil && !strings.Contains(string(data), blockStart) && !strings.Contains(string(data), conciseStart) {
				return nil, nil
			}
		}
		return &Operation{provider, "conflict", "guidance", path}, nil
	}
	if block == "" && count == 0 || block != "" && count == 1 && current == block {
		return nil, nil
	}
	action := "write-guidance"
	if block == "" {
		action = "remove-guidance"
		if strings.TrimSpace(user) != "" {
			action = "strip-guidance"
		}
	}
	return &Operation{provider, action, "guidance", path}, nil
}
