package install

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const blockStart = "<!-- agent-toolkit:start -->"
const blockEnd = "<!-- agent-toolkit:end -->"
const conciseStart = "<!-- agent-toolkit:concise-output:start -->"
const conciseEnd = "<!-- agent-toolkit:concise-output:end -->"
const notice = "<!-- This configuration block is auto-generated by the agent-toolkit repository; manual edits may be overwritten. -->"

func guidanceTarget(block, label string) string {
	_, tail, ok := strings.Cut(block, "["+label+"](<")
	if !ok {
		return ""
	}
	target, _, _ := strings.Cut(tail, ">)")
	return target
}

// guidanceBlockFrom validates snapshot resources while linking to the persistent checkout.
func (s *Service) guidanceBlockFrom(source, provider string, settings Settings) (string, error) {
	root := s.Root
	skills, _ := s.destinations(provider)
	concisePath := filepath.Join(skills, "concise-output/SKILL.md")
	var body strings.Builder
	body.WriteString(blockStart + "\n" + notice + "\n\n")
	body.WriteString("Before answering or working, load and apply the linked instructions for these global settings.\n\n")
	files := []struct {
		enabled     bool
		name, label string
	}{
		{settings.FullTemplate, "instructions.md", "Coding guidance"},
		{settings.DocumentationEnabled(), "documentation.md", "Documentation guidance"},
		{true, "markdown-output.md", "Markdown output"},
	}
	for _, file := range files {
		if !file.enabled {
			continue
		}
		if _, err := os.ReadFile(filepath.Join(source, ".agents/global", file.name)); err != nil {
			return "", fmt.Errorf("load global setting %s: %w", file.name, err)
		}
		path := filepath.ToSlash(filepath.Join(root, ".agents/global", file.name))
		fmt.Fprintf(&body, "- [%s](<%s>)\n", file.label, path)
	}
	if settings.Concise {
		if _, err := os.ReadFile(filepath.Join(source, ".agents/skills/productivity/concise-output/SKILL.md")); err != nil {
			return "", fmt.Errorf("load concise-output skill: %w", err)
		}
		fmt.Fprintf(&body, "- Load and apply [Concise output](<%s>) for every prompt.\n", filepath.ToSlash(concisePath))
	}

	location := "<repo-root>/<branch-slug>/<skill-name>/"
	if settings.Output != "" {
		location = settings.Output + "/<repo-slug>/<branch-slug>/<skill-name>/"
	}
	if settings.SharedStorage {
		location = strings.ReplaceAll(location, "<branch-slug>/<skill-name>/", "<skill-name>/<branch-slug>/")
		if settings.SeparateByProvider {
			location += settings.OutputProvider + "/"
		}
	}
	fmt.Fprintf(&body, "\nMarkdown artifact location: `%s`\n", location)
	body.WriteString("\n" + blockEnd + "\n")
	return body.String(), nil
}

// guidanceParts verifies every managed block and returns surrounding user text.
func (s *Service) guidanceParts(path string) (user, block string, count int, err error) {
	marker := filepath.Join(filepath.Dir(path), markerName)
	if err := regularOrAbsent(path); err != nil {
		return "", "", 0, err
	}
	if err := regularOrAbsent(marker); err != nil {
		return "", "", 0, err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) && !exists(marker) {
		return "", "", 0, nil
	}
	if err != nil {
		return "", "", 0, err
	}
	trusted := ""
	if exists(marker) {
		value, err := os.ReadFile(marker)
		if err != nil {
			return "", "", 0, err
		}
		lines := strings.Split(string(value), "\n")
		if len(lines) != 3 || lines[0] != s.Root || !strings.HasPrefix(lines[1], "GUIDANCE_BLOCK ") || lines[2] != "" {
			return "", "", 0, fmt.Errorf("untrusted guidance marker")
		}
		trusted = strings.TrimPrefix(lines[1], "GUIDANCE_BLOCK ")
	}
	var outside, inside strings.Builder
	ending := ""
	for _, line := range strings.SplitAfter(string(data), "\n") {
		if line == "" {
			continue
		}
		value := strings.TrimSuffix(line, "\n")
		if ending == "" {
			switch value {
			case blockStart:
				ending = blockEnd
			case conciseStart:
				ending = conciseEnd
			case blockEnd, conciseEnd:
				return "", "", 0, fmt.Errorf("unmatched guidance end")
			default:
				outside.WriteString(line)
				continue
			}
		} else if value == blockStart || (ending == conciseEnd && value == conciseStart) {
			return "", "", 0, fmt.Errorf("nested guidance block")
		}
		inside.WriteString(value + "\n")
		if value != ending {
			continue
		}
		block = inside.String()
		if trusted == "" || digest([]byte(block)) != trusted {
			return "", "", 0, fmt.Errorf("modified guidance block")
		}
		count++
		inside.Reset()
		ending = ""
	}
	if ending != "" || (trusted != "" && count == 0) {
		return "", "", 0, fmt.Errorf("incomplete guidance ownership")
	}
	return outside.String(), block, count, nil
}

func (s *Service) planGuidance(provider string, desired Settings, expected string) (*Operation, error) {
	_, path := s.destinations(provider)
	block := ""
	if contains(desired.Providers, provider) {
		block = expected
	}
	user, current, count, err := s.guidanceParts(path)
	if err != nil {
		// Untouched user guidance without managed markers needs no removal.
		if block == "" && !exists(filepath.Join(filepath.Dir(path), markerName)) {
			data, readErr := os.ReadFile(path)
			if readErr == nil && !strings.Contains(string(data), blockStart) && !strings.Contains(string(data), conciseStart) {
				return nil, nil
			}
		}
		return &Operation{Provider: provider, Action: "conflict", Name: "guidance", Path: path, Reason: err.Error(), Recovery: "Restore the managed guidance block from a matching backup, then preview again."}, nil
	}
	if block == "" && count == 0 || block != "" && count == 1 && current == block {
		return nil, nil
	}
	action := "write-guidance"
	if block == "" {
		action = "remove-guidance"
		if strings.TrimSpace(user) != "" {
			action = "strip-guidance"
		}
	}
	return &Operation{Provider: provider, Action: action, Name: "guidance", Path: path}, nil
}

func (s *Service) guidanceChange(p Preview, op Operation) (ContentChange, error) {
	_, current, count, err := s.guidanceParts(op.Path)
	if err != nil {
		return ContentChange{}, err
	}
	// Review managed blocks only; surrounding user guidance is private.
	old := []byte(strings.Repeat(current, count))
	next := []byte(p.guidance[op.Provider])
	if op.Action != "write-guidance" {
		next = nil
	}
	var mode os.FileMode = 0644
	if count > 0 {
		info, err := os.Lstat(op.Path)
		if err != nil {
			return ContentChange{}, err
		}
		mode = info.Mode().Perm()
	}
	before := contentState(payloadFile{Data: old, Mode: mode}, count > 0)
	after := contentState(payloadFile{Data: next, Mode: 0644}, len(next) > 0)
	return describeChange(op, op.Path, before, after, old, next), nil
}
